        /// <summary>
        /// Manually collect pending rent revenue (building rent + all leased flats).
        /// </summary>
        public bool CollectRent(out double collectedAmount)
        {
            collectedAmount = 0;
            double buildingRent = isOwned ? dailyRentIncome : 0;
            double flatRent = flatsRentedOut * flatDailyRent;
            double totalDue = buildingRent + flatRent;

            if (totalDue <= 0) return false;

            collectedAmount = totalDue;
            int currentDay = GetCurrentDay();

            if (GameManager.Instance != null && GameManager.Instance.Economy != null)
            {
                GameManager.Instance.Economy.ApplyTransaction(
                    collectedAmount,
                    TransactionCategory.Revenue,
                    $"Rent Income from {propertyName} (Building + {flatsRentedOut} Leased Flats)",
                    currentDay
                );
            }
            else
            {
                AddPlayerCashFallback(collectedAmount);
            }

            rentAvailableToCollect = false;
            SaveState();
            OnStateChanged?.Invoke(this);
            return true;
        }

        private void HandleDayCompleted(DailyReport report)
        {
            // Reset daily taxi rentals for the new day
            isTaxiRentedToday = false;
            currentlyRentedTaxis = 0;
            if (deployedTaxis != null)
            {
                foreach (var taxi in deployedTaxis)
                {
                    if (taxi != null) taxi.InitiateReturnToStation();
                }
                deployedTaxis.Clear();
            }

            // Calculate total daily rent
            double totalRent = 0;
            if (isOwned) totalRent += dailyRentIncome;
            totalRent += flatsRentedOut * flatDailyRent;

            if (totalRent > 0)
            {
                int currentDay = GetCurrentDay();
                if (GameManager.Instance != null && GameManager.Instance.Economy != null)
                {
                    GameManager.Instance.Economy.ApplyTransaction(
                        totalRent,
                        TransactionCategory.Revenue,
                        $"Daily Rent from {propertyName}",
                        currentDay
                    );
                }
                rentAvailableToCollect = true;
            }

            SaveState();
            OnStateChanged?.Invoke(this);
        }

        private double GetPlayerCash()
        {
            if (GameManager.Instance != null && GameManager.Instance.Economy != null)
            {
                return GameManager.Instance.Economy.Cash;
            }
            return PlayerPrefs.GetFloat("SavedPlayerCash", 10000f);
        }

        private void DeductPlayerCashFallback(double amount)
        {
            double cash = GetPlayerCash() - amount;
            PlayerPrefs.SetFloat("SavedPlayerCash", (float)Math.Max(0, cash));
            PlayerPrefs.Save();
        }

        private void AddPlayerCashFallback(double amount)
        {
            double cash = GetPlayerCash() + amount;
            PlayerPrefs.SetFloat("SavedPlayerCash", (float)cash);
            PlayerPrefs.Save();
        }

        private int GetCurrentDay()
        {
            if (GameManager.Instance != null && GameManager.Instance.Simulation != null)
            {
                return GameManager.Instance.Simulation.CurrentDay;
            }
            return 1;
        }

        public void SetSelectionMaterial(Material mat)
        {
            selectionShaderMaterial = mat;
        }

        public void SetConfig(string name, PropertyType type, double price, double dailyRent, string desc = "")
        {
            propertyName = name;
            propertyType = type;
            purchasePrice = price;
            dailyRentIncome = dailyRent;
            if (!string.IsNullOrEmpty(desc)) description = desc;

            if (type == PropertyType.Apartment)
            {
                hasFlats = true;
                totalFlats = 8;
                flatPurchasePrice = 5500;
                flatDailyRent = 280;
            }
            else if (type == PropertyType.House)
            {
                hasFlats = true;
                totalFlats = 3;
                flatPurchasePrice = 4000;
                flatDailyRent = 200;
            }
            else if (type != PropertyType.TaxiStation && type != PropertyType.Stadium)
            {
                hasFlats = true;
                totalFlats = 6;
                flatPurchasePrice = 4500;
                flatDailyRent = 220;
            }
        }

        public void SetTaxiConfig(double rentFee, double fareRevenue)
        {
            taxiRentalFee = rentFee;
            dailyFareRevenue = fareRevenue;
        }

        private void SaveState()
        {
            string key = $"Property_{gameObject.name}_{propertyName}".Replace(" ", "_");
            PlayerPrefs.SetInt($"{key}_Owned", isOwned ? 1 : 0);
            PlayerPrefs.SetInt($"{key}_TaxiRented", isTaxiRentedToday ? 1 : 0);
            PlayerPrefs.SetInt($"{key}_RentedTaxisCount", currentlyRentedTaxis);
            PlayerPrefs.SetInt($"{key}_LastRentDay", lastTaxiRentDay);
            PlayerPrefs.SetInt($"{key}_FlatsOwned", flatsOwned);
            PlayerPrefs.SetInt($"{key}_FlatsRentedOut", flatsRentedOut);
            PlayerPrefs.SetInt($"{key}_MatchesHosted", matchesHosted);
            PlayerPrefs.SetFloat($"{key}_MatchRevenue", (float)totalMatchRevenue);
            PlayerPrefs.Save();
        }

        private void LoadState()
        {
            string key = $"Property_{gameObject.name}_{propertyName}".Replace(" ", "_");
            if (PlayerPrefs.HasKey($"{key}_Owned"))
            {
                isOwned = PlayerPrefs.GetInt($"{key}_Owned") == 1;
            }
            if (PlayerPrefs.HasKey($"{key}_TaxiRented"))
            {
                isTaxiRentedToday = PlayerPrefs.GetInt($"{key}_TaxiRented") == 1;
            }
            if (PlayerPrefs.HasKey($"{key}_RentedTaxisCount"))
            {
                currentlyRentedTaxis = PlayerPrefs.GetInt($"{key}_RentedTaxisCount");
            }
            if (PlayerPrefs.HasKey($"{key}_LastRentDay"))
            {
                lastTaxiRentDay = PlayerPrefs.GetInt($"{key}_LastRentDay");
            }
            if (PlayerPrefs.HasKey($"{key}_FlatsOwned"))
            {
                flatsOwned = PlayerPrefs.GetInt($"{key}_FlatsOwned");
            }
            if (PlayerPrefs.HasKey($"{key}_FlatsRentedOut"))
            {
                flatsRentedOut = PlayerPrefs.GetInt($"{key}_FlatsRentedOut");
            }
            if (PlayerPrefs.HasKey($"{key}_MatchesHosted"))
            {
                matchesHosted = PlayerPrefs.GetInt($"{key}_MatchesHosted");
            }
            if (PlayerPrefs.HasKey($"{key}_MatchRevenue"))
            {
                totalMatchRevenue = PlayerPrefs.GetFloat($"{key}_MatchRevenue");
            }
        }
