        #region Taxi Station Fleet Operations (Max 8 per station)
        public void EnsureTaxiStationFleet()
        {
            if (propertyType != PropertyType.TaxiStation) return;

            if (parkedStationTaxis == null) parkedStationTaxis = new List<GameObject>();
            parkedStationTaxis.RemoveAll(x => x == null);

            if (parkedStationTaxis.Count == 0)
            {
                Transform[] children = GetComponentsInChildren<Transform>(true);
                foreach (var child in children)
                {
                    if (child == null || child == transform) continue;
                    string cName = child.name.ToLower();
                    if ((cName.Contains("taxi") || cName.Contains("texi")) &&
                        !cName.Contains("spawn") &&
                        !cName.Contains("wheel") &&
                        child.parent == transform)
                    {
                        if (!parkedStationTaxis.Contains(child.gameObject))
                        {
                            parkedStationTaxis.Add(child.gameObject);
                        }
                    }
                }
            }

            if (taxiExitPoint == null)
            {
                Transform spawnPoint = transform.Find("Texi Spawn Point");
                if (spawnPoint != null) taxiExitPoint = spawnPoint;
            }
        }

        /// <summary>
        /// Rents a taxi from this station (maximum 8 taxis per station).
        /// When rented, one physical taxi departs the station and enters the road traffic,
        /// generating periodic random passenger fares until the day ends.
        /// </summary>
        public bool RentStationTaxi(out string feedbackMessage)
        {
            feedbackMessage = "";
            if (propertyType != PropertyType.TaxiStation)
            {
                feedbackMessage = "Taxis can only be rented at a Taxi Station!";
                return false;
            }

            if (currentlyRentedTaxis >= maxRentableTaxis)
            {
                feedbackMessage = $"Maximum of {maxRentableTaxis} taxis already rented from this station today!";
                return false;
            }

            double currentCash = GetPlayerCash();
            if (currentCash < taxiRentalFee)
            {
                feedbackMessage = $"Insufficient funds! You need ${taxiRentalFee:N0} to rent a taxi for today.";
                return false;
            }

            int currentDay = GetCurrentDay();

            // Deduct rental fee
            if (GameManager.Instance != null && GameManager.Instance.Economy != null)
            {
                bool success = GameManager.Instance.Economy.ApplyTransaction(
                    -taxiRentalFee,
                    TransactionCategory.OperatingExpense,
                    $"Taxi #{currentlyRentedTaxis + 1} Rental Fee (1 Day)",
                    currentDay
                );
                if (!success) return false;
            }
            else
            {
                DeductPlayerCashFallback(taxiRentalFee);
            }

            currentlyRentedTaxis++;
            isTaxiRentedToday = true;
            lastTaxiRentDay = currentDay;

            // Deploy one physical taxi out to the road
            DeployOneTaxi(currentlyRentedTaxis);

            SaveState();
            feedbackMessage = $"Taxi #{currentlyRentedTaxis} (of {maxRentableTaxis}) rented! It is now driving on the streets collecting passenger fares for your account.";
            Debug.Log($"[PropertyBuilding] {feedbackMessage}");
            OnStateChanged?.Invoke(this);
            return true;
        }

        public bool RentTaxiForDay(out string feedbackMessage)
        {
            return RentStationTaxi(out feedbackMessage);
        }

        private void DeployOneTaxi(int taxiNum)
        {
            EnsureTaxiStationFleet();

            // Select a parked taxi as a visual template WITHOUT moving it
            GameObject templateTaxi = null;
            if (parkedStationTaxis.Count > 0 && parkedStationTaxis[0] != null)
            {
                templateTaxi = parkedStationTaxis[0];
            }
            else
            {
                // Fallback: search any child vehicle model
                foreach (Transform child in transform)
                {
                    if (child.name.ToLower().Contains("taxi") || child.name.ToLower().Contains("texi"))
                    {
                        templateTaxi = child.gameObject;
                        break;
                    }
                }
            }

            if (templateTaxi == null)
            {
                Debug.LogWarning("[PropertyBuilding] No taxi vehicle model available as template to spawn!");
                return;
            }

            // Spawn a brand new taxi instance at the station exit point
            Vector3 spawnPos = taxiExitPoint != null ? taxiExitPoint.position : transform.position + transform.forward * 4f;
            Quaternion spawnRot = taxiExitPoint != null ? taxiExitPoint.rotation : transform.rotation;

            GameObject spawnedTaxi = Instantiate(templateTaxi, spawnPos, spawnRot);
            spawnedTaxi.name = $"Spawned_Rented_Taxi_{taxiNum}";
            spawnedTaxi.transform.SetParent(null, true); // Keep scene root clean

            // Find nearest road network starting waypoint
            EmpireBuilder.Traffic.TrafficWaypointNode startNode = FindNearestRoadWaypoint(spawnPos);
            GameObject roadNet = startNode != null ? startNode.NetworkRoot?.gameObject : null;

            var rentedComp = spawnedTaxi.GetComponent<EmpireBuilder.Traffic.ActiveRentedTaxi>();
            if (rentedComp == null)
            {
                rentedComp = spawnedTaxi.AddComponent<EmpireBuilder.Traffic.ActiveRentedTaxi>();
            }

            rentedComp.SetupSpawnedTaxi(this, taxiNum, taxiExitPoint, startNode, roadNet, taxiShiftDurationSeconds, taxiGreenMarkerSprite);

            if (!deployedTaxis.Contains(rentedComp))
            {
                deployedTaxis.Add(rentedComp);
            }
        }

        public void NotifyTaxiDespawned(EmpireBuilder.Traffic.ActiveRentedTaxi taxi)
        {
            if (deployedTaxis != null && taxi != null)
            {
                deployedTaxis.Remove(taxi);
            }
        }

        private EmpireBuilder.Traffic.TrafficWaypointNode FindNearestRoadWaypoint(Vector3 pos)
        {
            var nodes = UnityEngine.Object.FindObjectsByType<EmpireBuilder.Traffic.TrafficWaypointNode>(FindObjectsInactive.Exclude, FindObjectsSortMode.None);
            EmpireBuilder.Traffic.TrafficWaypointNode closest = null;
            float minDist = float.MaxValue;
            foreach (var n in nodes)
            {
                if (n == null) continue;
                float d = Vector3.Distance(pos, n.Position);
                if (d < minDist)
                {
                    minDist = d;
                    closest = n;
                }
            }
            return closest;
        }
