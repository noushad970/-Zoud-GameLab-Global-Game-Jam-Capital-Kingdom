        private void DeductPlayerCashFallback(double amount)
        {
            double cash = GetPlayerCash() - amount;
            PlayerPrefs.SetFloat("SavedPlayerCash", (float)Math.Max(0, cash));
            PlayerPrefs.Save();
        }

        private void AddPlayerCashFallback(double amount)
        {
            double cash = GetPlayerCash() + amount;
            PlayerPrefs.SetFloat("SavedPlayerCash", (float)cash);
            PlayerPrefs.Save();
        }

