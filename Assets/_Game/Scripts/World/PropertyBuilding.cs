        /// <summary>
        /// Manually collect pending rent revenue (building rent + all leased flats).
        /// </summary>
        public bool CollectRent(out double collectedAmount)
        {
            collectedAmount = 0;
            double buildingRent = isOwned ? dailyRentIncome : 0;
            double flatRent = flatsRentedOut * flatDailyRent;
            double totalDue = buildingRent + flatRent;

            if (totalDue <= 0) return false;

            collectedAmount = totalDue;
            int currentDay = GetCurrentDay();

            if (GameManager.Instance != null && GameManager.Instance.Economy != null)
            {
                GameManager.Instance.Economy.ApplyTransaction(
                    collectedAmount,
                    TransactionCategory.Revenue,
                    $"Rent Income from {propertyName} (Building + {flatsRentedOut} Leased Flats)",
                    currentDay
                );
            }
            else
            {
                AddPlayerCashFallback(collectedAmount);
            }

            rentAvailableToCollect = false;
            SaveState();
            OnStateChanged?.Invoke(this);
            return true;
        }

        private void HandleDayCompleted(DailyReport report)
        {
            // Reset daily taxi rentals for the new day
            isTaxiRentedToday = false;
            currentlyRentedTaxis = 0;
            if (deployedTaxis != null)
            {
                foreach (var taxi in deployedTaxis)
                {
                    if (taxi != null) taxi.InitiateReturnToStation();
                }
                deployedTaxis.Clear();
            }

            // Calculate total daily rent
            double totalRent = 0;
            if (isOwned) totalRent += dailyRentIncome;
            totalRent += flatsRentedOut * flatDailyRent;

            if (totalRent > 0)
            {
                int currentDay = GetCurrentDay();
                if (GameManager.Instance != null && GameManager.Instance.Economy != null)
                {
                    GameManager.Instance.Economy.ApplyTransaction(
                        totalRent,
                        TransactionCategory.Revenue,
                        $"Daily Rent from {propertyName}",
                        currentDay
                    );
                }
                rentAvailableToCollect = true;
            }

            SaveState();
            OnStateChanged?.Invoke(this);
        }

        private double GetPlayerCash()
        {
            if (GameManager.Instance != null && GameManager.Instance.Economy != null)
